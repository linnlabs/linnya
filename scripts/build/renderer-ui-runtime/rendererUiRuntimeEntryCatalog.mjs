export const rendererUiPluginRuntimeEntries = Object.freeze(
  rendererUiRuntimeEntries.filter(item => item.pluginRuntimeExternal),
);

function entry(id, specifier, packageExport, canonicalSource, protocolFile, namedExports) {
  return Object.freeze({
    id,
    specifier,
    packageExport,
    canonicalSource,
    cssOnly: false,
    pluginRuntimeExternal: true,
    hostModuleKey: specifier,
    protocolUrl: `plugin://host/renderer-ui/${protocolFile}`,
    namedExports: Object.freeze(namedExports),
  });
}

/**
 * 不依赖 Vue、DOM、CSS 或 Host 状态的纯叶子入口由 consumer 直接打包，避免给 hidden worker
 * 人为引入 plugin:// Host runtime。它仍登记在同一目录中，确保 package export、resolver 与 artifact
 * 交付策略可以被统一审计。
 */
function bundledEntry(id, specifier, packageExport, canonicalSource, namedExports) {
  return Object.freeze({
    id,
    specifier,
    packageExport,
    canonicalSource,
    cssOnly: false,
    pluginRuntimeExternal: false,
    hostModuleKey: null,
    protocolUrl: null,
    namedExports: Object.freeze(namedExports),
  });
}

function asset(specifier, packageExport, canonicalSource) {
  return Object.freeze({
    id: null,
    specifier,
    packageExport,
    canonicalSource,
    cssOnly: true,
    pluginRuntimeExternal: false,
    hostModuleKey: null,
    protocolUrl: null,
    namedExports: Object.freeze([]),
  });
}

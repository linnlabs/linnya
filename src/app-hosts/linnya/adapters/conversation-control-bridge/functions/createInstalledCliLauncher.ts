import path from 'node:path';

export interface InstalledCliLauncher {
  /** 用户级固定入口；外部 Agent 的 Skill 只认这个位置，不关心 App 装在哪里。 */
  readonly filePath: string;
  readonly content: string;
}

interface InstalledCliLauncherInput {
  readonly platform: NodeJS.Platform;
  readonly homeDirectory: string;
  /** 安装包的 Resources 目录；随包 CLI 产物位于其下的 `linnya-cli/`。 */
  readonly resourcesPath: string;
  /** App Server 自己所用的随包 Node。入口复用它，因此不要求用户另装 Node。 */
  readonly nodeExecutablePath: string;
}

/**
 * App 不在记录位置时的回执。字段与 CLI 的错误 JSON 一致，调用方按同一套退出码 3 处理；
 * 文本里不能出现单引号、百分号和重定向符号，它会原样嵌进 sh 与 cmd 两种脚本。
 */
const MISSING_INSTALLATION_ERROR = JSON.stringify({
  schema_version: 1,
  ok: false,
  connection: { source_root: null, branch: null, state: 'not_connected', instance: null },
  error: {
    code: 'app_not_running',
    message: 'Linnya is not at the recorded location (it may have been moved or removed). '
      + 'Open the Linnya desktop app once to refresh this command.',
    retryable: false,
  },
});

function quoteForPosixShell(value: string): string {
  return `'${value.replace(/'/gu, "'\\''")}'`;
}

/**
 * cmd 按系统代码页解码批处理文本，中文用户名会被读坏；安装目录位于用户主目录下时改写成
 * `%USERPROFILE%` 相对形式，由 cmd 在运行时展开成正确的 Unicode 路径。当前安装器只装到
 * 用户主目录内（NSIS oneClick、perMachine=false）。
 */
function toWindowsBatchPath(value: string, homeDirectory: string): string {
  const relative = path.win32.relative(homeDirectory, value);
  const insideHome = relative !== '' && !relative.startsWith('..') && !path.win32.isAbsolute(relative);
  // 批处理里字面量百分号要写成两个；前缀的 %USERPROFILE% 是有意留给 cmd 展开的变量。
  const escapeLiteral = (text: string): string => text.replace(/%/gu, '%%');
  return insideHome ? `%USERPROFILE%\\${escapeLiteral(relative)}` : escapeLiteral(value);
}

/**
 * 生成指向当前安装位置的 `linnya` 入口脚本。
 *
 * 入口每次启动都按当前安装位置重写，所以移动 App 或升级后重新打开一次即可；它不进系统 PATH，
 * 只服务外部 Agent 的 Skill。脚本本身不含连接凭据，凭据仍只在连接描述文件里。
 */
export function createInstalledCliLauncher(input: InstalledCliLauncherInput): InstalledCliLauncher {
  if (input.platform === 'win32') {
    const join = path.win32.join;
    const node = toWindowsBatchPath(input.nodeExecutablePath, input.homeDirectory);
    const cli = toWindowsBatchPath(
      join(input.resourcesPath, 'linnya-cli', 'bin', 'linnya.cjs'),
      input.homeDirectory,
    );
    return Object.freeze({
      filePath: join(input.homeDirectory, '.linnya', 'bin', 'linnya.cmd'),
      content: [
        '@echo off',
        'rem Generated by the Linnya desktop app on startup. Do not edit.',
        'setlocal',
        `set "LINNYA_NODE=${node}"`,
        `set "LINNYA_CLI=${cli}"`,
        'if not exist "%LINNYA_NODE%" goto missing',
        'if not exist "%LINNYA_CLI%" goto missing',
        '"%LINNYA_NODE%" "%LINNYA_CLI%" %*',
        'exit /b %ERRORLEVEL%',
        ':missing',
        `echo ${MISSING_INSTALLATION_ERROR} 1>&2`,
        'exit /b 3',
        '',
      ].join('\r\n'),
    });
  }
  const join = path.posix.join;
  return Object.freeze({
    filePath: join(input.homeDirectory, '.linnya', 'bin', 'linnya'),
    content: [
      '#!/bin/sh',
      '# Generated by the Linnya desktop app on startup. Do not edit.',
      `NODE=${quoteForPosixShell(input.nodeExecutablePath)}`,
      `CLI=${quoteForPosixShell(join(input.resourcesPath, 'linnya-cli', 'bin', 'linnya.cjs'))}`,
      'if [ ! -x "$NODE" ] || [ ! -f "$CLI" ]; then',
      `  printf '%s\\n' ${quoteForPosixShell(MISSING_INSTALLATION_ERROR)} >&2`,
      '  exit 3',
      'fi',
      'exec "$NODE" "$CLI" "$@"',
      '',
    ].join('\n'),
  });
}
